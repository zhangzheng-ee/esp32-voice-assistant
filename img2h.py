# -*- coding: utf-8 -*-
"""
img2h.py  ——  把任意图片转成 Arduino_GFX 能直接画的 RGB565 数组

用法:
    python img2h.py 图片路径 [输出.h]

例:
    python img2h.py D:\\zz187\\Pictures\\cat.jpg
    -> 生成 D:\\zz187\\Pictures\\cat.h

要求:
    pip install pillow
"""
import sys
import os

try:
    from PIL import Image
except ImportError:
    print("缺少 Pillow，请先运行: pip install pillow")
    sys.exit(1)

W = 240
H = 240


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return

    src = sys.argv[1]
    if not os.path.isfile(src):
        print("找不到文件:", src)
        return

    out = sys.argv[2] if len(sys.argv) > 2 else os.path.splitext(src)[0] + ".h"

    im = Image.open(src).convert("RGB")
    print("原图:", im.width, "x", im.height)

    # 等比缩放到能塞进 240x240
    im.thumbnail((W, H), Image.LANCZOS)

    # 居中贴到黑底画布上
    canvas = Image.new("RGB", (W, H), (0, 0, 0))
    canvas.paste(im, ((W - im.width) // 2, (H - im.height) // 2))

    px = canvas.load()
    vals = []
    for y in range(H):
        for x in range(W):
            r, g, b = px[x, y]
            # RGB888 -> RGB565
            vals.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))

    with open(out, "w", encoding="utf-8") as f:
        f.write("// generated by img2h.py  %dx%d RGB565\n" % (W, H))
        f.write("#pragma once\n\n")
        f.write("#define IMG_W %d\n" % W)
        f.write("#define IMG_H %d\n\n" % H)
        f.write("const uint16_t image_data[%d] = {\n" % (W * H))
        for i in range(0, len(vals), 12):
            f.write("    " + ",".join("0x%04X" % v for v in vals[i:i + 12]) + ",\n")
        f.write("};\n")

    print("已生成:", out)
    print("文件大小: %.1f KB" % (os.path.getsize(out) / 1024.0))
    print("记得把 image.h 放到和 .ino 同一个文件夹里")


if __name__ == "__main__":
    main()