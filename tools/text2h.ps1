param(
    [Parameter(Mandatory = $true)][string]$Text,
    [string]$OutputPath = "D:\zz187\Arduino\experiments\plantest\image.h",
    [int]$Size = 240,
    [int]$FontSize = 36,
    [string]$FontName = "Microsoft YaHei",
    [string]$TextColor = "255,255,255",
    [string]$BgColor = "0,0,0"
)

# text2h.ps1 —— 把一段文字渲染成 240x240 图像，转成 Arduino_GFX 的 RGB565 数组
# 用法:
#   .\text2h.ps1 -Text "你好|张正"
#   .\text2h.ps1 -Text "Hello" -FontSize 48 -TextColor "0,255,255"
# 多行用 | 分隔

Add-Type -AssemblyName System.Drawing

function Parse-Rgb([string]$s) {
    $p = $s -split ','
    return [System.Drawing.Color]::FromArgb([int]$p[0], [int]$p[1], [int]$p[2])
}

$fg = Parse-Rgb $TextColor
$bg = Parse-Rgb $BgColor

$lines = $Text -split '\|'
if ($lines.Count -eq 0) { $lines = @($Text) }

$bmp = New-Object System.Drawing.Bitmap($Size, $Size, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
$gr = [System.Drawing.Graphics]::FromImage($bmp)
$gr.Clear($bg)
$gr.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
$gr.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::AntiAliasGridFit

$font = New-Object System.Drawing.Font($FontName, $FontSize, [System.Drawing.FontStyle]::Bold)
$brush = New-Object System.Drawing.SolidBrush($fg)

$fmt = New-Object System.Drawing.StringFormat
$fmt.Alignment = [System.Drawing.StringAlignment]::Center
$fmt.LineAlignment = [System.Drawing.StringAlignment]::Center

$lineH = [int]($FontSize * 1.45)
$totalH = $lineH * $lines.Count
$startY = [int](($Size - $totalH) / 2)

for ($i = 0; $i -lt $lines.Count; $i++) {
    $rect = New-Object System.Drawing.RectangleF(0, ($startY + $i * $lineH), $Size, $lineH)
    $gr.DrawString($lines[$i], $font, $brush, $rect, $fmt)
}

$font.Dispose()
$brush.Dispose()
$gr.Dispose()

# ---- 转 RGB565 ----
$rect2 = New-Object System.Drawing.Rectangle(0, 0, $Size, $Size)
$data = $bmp.LockBits($rect2, [System.Drawing.Imaging.ImageLockMode]::ReadOnly, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
$stride = $data.Stride
$buf = New-Object byte[] ($stride * $Size)
[System.Runtime.InteropServices.Marshal]::Copy($data.Scan0, $buf, 0, $buf.Length)
$bmp.UnlockBits($data)
$bmp.Dispose()

$rows = New-Object System.Collections.Generic.List[string]
for ($y = 0; $y -lt $Size; $y++) {
    $row = New-Object string[] $Size
    $base = $y * $stride
    for ($x = 0; $x -lt $Size; $x++) {
        $i = $base + $x * 4
        $b = [int]$buf[$i]
        $gg = [int]$buf[$i + 1]
        $r = [int]$buf[$i + 2]
        $v = ((($r -band 0xF8) -shl 8) -bor (($gg -band 0xFC) -shl 3) -bor ($b -shr 3))
        $row[$x] = ("0x{0:X4}" -f $v)
    }
    $rows.Add("    " + ($row -join ",") + ",")
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// generated by text2h.ps1  ${Size}x${Size} RGB565")
[void]$sb.AppendLine("#pragma once")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("#define IMG_W $Size")
[void]$sb.AppendLine("#define IMG_H $Size")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("const uint16_t image_data[$($Size * $Size)] = {")
foreach ($r in $rows) { [void]$sb.AppendLine($r) }
[void]$sb.AppendLine("};")

$sb.ToString() | Out-File -FilePath $OutputPath -Encoding ascii

$kb = [Math]::Round((Get-Item -LiteralPath $OutputPath).Length / 1024, 1)
Write-Host "已生成: $OutputPath  ($kb KB)"
Write-Host "内容: $($lines -join ' / ')"
Write-Host "回 Arduino IDE 点上传即可。"