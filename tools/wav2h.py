# -*- coding: utf-8 -*-
"""
WAV -> C 数组 (.h)
用法:
  python wav2h.py <in.wav> [out.h]
说明:
  - 只支持 16bit PCM WAV
  - 多声道自动混成单声道
  - 输出 const int16_t audio_data[]，放在 flash 里
"""
import sys, os, wave
import numpy as np

if len(sys.argv) < 2:
    print("用法: python wav2h.py <in.wav> [out.h]")
    sys.exit(1)

src = sys.argv[1]
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.splitext(src)[0] + ".h"

w = wave.open(src, "rb")
sr, ch, sw, n = w.getframerate(), w.getnchannels(), w.getsampwidth(), w.getnframes()
raw = w.readframes(n)
w.close()

if sw != 2:
    print(f"[X] 只支持 16bit，当前 {sw*8}bit。先用 ffmpeg 转: -c:a pcm_s16le")
    sys.exit(1)

x = np.frombuffer(raw, dtype=np.int16)
if ch > 1:
    x = x.reshape(-1, ch).mean(axis=1).astype(np.int16)

dur = len(x) / sr
peak = int(np.max(np.abs(x.astype(np.int32))))
print(f"输入  {os.path.basename(src)}")
print(f"采样率 {sr} Hz   声道 {ch} -> 1   样本 {len(x)}   时长 {dur:.2f}s")
print(f"峰值   {peak} ({peak/32768*100:.1f}% FS)")

if dur > 30:
    print(f"[!] 时长 {dur:.1f}s 偏长，flash 会吃紧（约 {len(x)*2/1024:.0f} KB）")

with open(dst, "w", encoding="utf-8", newline="\n") as f:
    f.write(f"// auto-generated by wav2h.py\n")
    f.write(f"// src: {os.path.basename(src)}\n")
    f.write(f"// {sr} Hz, mono, 16bit, {dur:.2f}s, {len(x)} samples\n")
    f.write("#pragma once\n")
    f.write(f"#define AUDIO_SR  {sr}\n")
    f.write(f"#define AUDIO_LEN {len(x)}\n")
    f.write(f"#define AUDIO_MS  {int(dur*1000)}\n\n")
    f.write("const int16_t audio_data[AUDIO_LEN] = {\n")
    for i in range(0, len(x), 16):
        chunk = x[i:i+16]
        f.write(",".join(str(int(v)) for v in chunk))
        f.write(",\n")
    f.write("};\n")

size = os.path.getsize(dst)
print(f"\n输出  {dst}")
print(f"体积  {size/1024:.0f} KB (文本)  -> 编译后约 {len(x)*2/1024:.0f} KB flash")
print(f"可用  #define AUDIO_SR {sr} / AUDIO_LEN {len(x)} / AUDIO_MS {int(dur*1000)}")