param(
    [Parameter(Mandatory = $true)][string]$ImagePath,
    [string]$OutputPath = "",
    [int]$Size = 240
)

$ErrorActionPreference = 'Stop'

if (-not (Test-Path -LiteralPath $ImagePath)) {
    Write-Host "[X] 找不到文件: $ImagePath" -ForegroundColor Red
    exit 1
}

if ([string]::IsNullOrWhiteSpace($OutputPath)) {
    $OutputPath = [System.IO.Path]::ChangeExtension($ImagePath, '.h')
}

$cs = @'
using System;
using System.Drawing;
using System.Drawing.Drawing2D;
using System.Drawing.Imaging;
using System.Runtime.InteropServices;
using System.Text;

public class ImgConv {
    public static int LastW = 0;
    public static int LastH = 0;
    public static int SrcW = 0;
    public static int SrcH = 0;

    public static string ToRgb565(string srcPath, int size) {
        using (var src = new Bitmap(srcPath)) {
            SrcW = src.Width; SrcH = src.Height;
            double scale = Math.Min((double)size / src.Width, (double)size / src.Height);
            int nw = (int)Math.Round(src.Width * scale);
            int nh = (int)Math.Round(src.Height * scale);
            if (nw < 1) nw = 1;
            if (nh < 1) nh = 1;
            LastW = nw; LastH = nh;

            using (var bmp = new Bitmap(size, size, PixelFormat.Format32bppArgb)) {
                using (var g = Graphics.FromImage(bmp)) {
                    g.Clear(Color.Black);
                    g.InterpolationMode = InterpolationMode.HighQualityBicubic;
                    g.PixelOffsetMode = PixelOffsetMode.HighQuality;
                    g.DrawImage(src, (size - nw) / 2, (size - nh) / 2, nw, nh);
                }

                var data = bmp.LockBits(new Rectangle(0, 0, size, size),
                                        ImageLockMode.ReadOnly, PixelFormat.Format32bppArgb);
                int stride = data.Stride;
                byte[] buf = new byte[stride * size];
                Marshal.Copy(data.Scan0, buf, 0, buf.Length);
                bmp.UnlockBits(data);

                var sb = new StringBuilder(size * size * 7 + 8192);
                for (int y = 0; y < size; y++) {
                    int rowBase = y * stride;
                    for (int x = 0; x < size; x++) {
                        int i = rowBase + x * 4;
                        int b = buf[i];
                        int gg = buf[i + 1];
                        int r = buf[i + 2];
                        int v = ((r & 0xF8) << 8) | ((gg & 0xFC) << 3) | (b >> 3);
                        sb.Append("0x").Append(v.ToString("X4"));
                        if (x < size - 1) sb.Append(',');
                    }
                    sb.Append(",\r\n");
                }
                return sb.ToString();
            }
        }
    }

    public static void Probe(string srcPath) {
        using (var src = new Bitmap(srcPath)) {
            SrcW = src.Width; SrcH = src.Height;
        }
    }
}
'@

Write-Host "[1/3] 编译转换器..." -ForegroundColor Cyan
Add-Type -ReferencedAssemblies System.Drawing -TypeDefinition $cs -ErrorAction Stop

Write-Host "[2/3] 读取并缩放..." -ForegroundColor Cyan
$sw = [System.Diagnostics.Stopwatch]::StartNew()
try {
    $body = [ImgConv]::ToRgb565($ImagePath, $Size)
} catch {
    Write-Host "[X] 读图失败: $($_.Exception.Message)" -ForegroundColor Red
    Write-Host "    可能是 HEIC/WebP 这类格式，先用画图另存为 JPG 再试。" -ForegroundColor Yellow
    exit 1
}
$sw.Stop()

Write-Host ("      源图 {0}x{1}  ->  {2}x{3} 居中黑底, 用时 {4} ms" -f [ImgConv]::SrcW, [ImgConv]::SrcH, [ImgConv]::LastW, [ImgConv]::LastH, $sw.ElapsedMilliseconds) -ForegroundColor Gray

$header = "// generated by img2h.ps1  ${Size}x${Size} RGB565`r`n#pragma once`r`n`r`n#define IMG_W $Size`r`n#define IMG_H $Size`r`n`r`nconst uint16_t image_data[$($Size * $Size)] = {`r`n"
$footer = "};`r`n"

$outDir = Split-Path -Parent $OutputPath
if ($outDir -and -not (Test-Path -LiteralPath $outDir)) {
    New-Item -ItemType Directory -Path $outDir -Force | Out-Null
}

Write-Host "[3/3] 写入头文件..." -ForegroundColor Cyan
($header + $body + $footer) | Out-File -LiteralPath $OutputPath -Encoding ascii

$kb = [Math]::Round((Get-Item -LiteralPath $OutputPath).Length / 1024, 1)
Write-Host ""
Write-Host "[OK] $OutputPath  $kb KB" -ForegroundColor Green
Write-Host "     回 Arduino IDE 点上传即可。" -ForegroundColor Green